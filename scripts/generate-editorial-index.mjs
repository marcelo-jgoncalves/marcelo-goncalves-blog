#!/usr/bin/env node
// Deterministic portfolio index generator (Fase D, prompt-evolucao-subsistema-editorial.md §14).
// Reads every plan's front matter and emits editorial/index.generated.json
// and editorial/index.generated.md. Never hand-edit those two files — this
// script is the only writer. CI runs it and diffs the result against what's
// committed (see --check) to catch a stale index.

import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');
const PLANS_DIR = path.join(REPO_ROOT, 'editorial', 'plans');
const JSON_OUT = path.join(REPO_ROOT, 'editorial', 'index.generated.json');
const MD_OUT = path.join(REPO_ROOT, 'editorial', 'index.generated.md');

const INDEX_FIELDS = [
  'id',
  'title',
  'status',
  'content_pillar',
  'series',
  'audience',
  'intent',
  'priority',
  'created_at',
  'planned_publication',
  'published_at',
  'canonical_content',
];

function listPlanFiles(dir) {
  const results = [];
  for (const entry of readdirSync(dir)) {
    const full = path.join(dir, entry);
    const st = statSync(full);
    if (st.isDirectory()) {
      if (entry === 'templates') continue;
      results.push(...listPlanFiles(full));
    } else if (entry.endsWith('.md') && entry !== 'README.md') {
      results.push(full);
    }
  }
  return results;
}

function parseFrontMatter(raw) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!match) return null;
  try {
    return yaml.load(match[1], { schema: yaml.JSON_SCHEMA }) ?? {};
  } catch {
    return null;
  }
}

function buildEntries() {
  const entries = [];
  for (const file of listPlanFiles(PLANS_DIR)) {
    const raw = readFileSync(file, 'utf8');
    const data = parseFrontMatter(raw);
    if (!data || !data.id) continue; // unparseable files are the validator's job to flag, not the index's
    const entry = {};
    for (const field of INDEX_FIELDS) {
      entry[field] = data[field] ?? null;
    }
    entry.path = path.relative(REPO_ROOT, file).split(path.sep).join('/');
    entries.push(entry);
  }
  // Deterministic order: id is the stable identifier plans are referenced
  // by everywhere else in the system, so sort on it rather than
  // created_at/title (either of which could tie or be edited).
  entries.sort((a, b) => a.id.localeCompare(b.id));
  return entries;
}

function toJson(entries) {
  return JSON.stringify(
    {
      schema_version: '1.0',
      generated_note: 'Generated by scripts/generate-editorial-index.mjs. Do not hand-edit.',
      count: entries.length,
      plans: entries,
    },
    null,
    2
  ) + '\n';
}

function toMarkdown(entries) {
  const lines = [
    '# Editorial Portfolio Index',
    '',
    '> Generated by `scripts/generate-editorial-index.mjs`. Do not hand-edit — run `npm run generate:editorial-index` after adding or updating a plan.',
    '',
    `Total: ${entries.length} plan(s).`,
    '',
    '| ID | Title | Status | Pillar | Series | Priority | Created | Planned pub. | Published |',
    '|---|---|---|---|---|---|---|---|---|',
  ];
  for (const e of entries) {
    const cell = (v) => (v === null || v === undefined || v === '' ? '—' : String(v).replace(/\|/g, '\\|'));
    lines.push(
      `| ${cell(e.id)} | ${cell(e.title)} | ${cell(e.status)} | ${cell(e.content_pillar)} | ${cell(e.series)} | ${cell(e.priority)} | ${cell(e.created_at)} | ${cell(e.planned_publication)} | ${cell(e.published_at)} |`
    );
  }
  lines.push('');
  return lines.join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  const entries = buildEntries();
  const json = toJson(entries);
  const md = toMarkdown(entries);

  if (check) {
    const currentJson = existsOrEmpty(JSON_OUT);
    const currentMd = existsOrEmpty(MD_OUT);
    const jsonStale = currentJson !== json;
    const mdStale = currentMd !== md;
    if (jsonStale || mdStale) {
      console.error('Editorial portfolio index is stale.');
      if (jsonStale) console.error(`  - ${path.relative(REPO_ROOT, JSON_OUT)} out of date`);
      if (mdStale) console.error(`  - ${path.relative(REPO_ROOT, MD_OUT)} out of date`);
      console.error('Run `npm run generate:editorial-index` and commit the result.');
      process.exit(1);
    }
    console.log(`Editorial portfolio index is up to date (${entries.length} plans).`);
    process.exit(0);
  }

  writeFileSync(JSON_OUT, json);
  writeFileSync(MD_OUT, md);
  console.log(`Generated editorial index for ${entries.length} plans.`);
}

function existsOrEmpty(file) {
  try {
    return readFileSync(file, 'utf8');
  } catch {
    return '';
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}

export { buildEntries, toJson, toMarkdown };
